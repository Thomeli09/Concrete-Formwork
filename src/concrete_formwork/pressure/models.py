"""Extensible, additive pressure contributions for staged concrete pours.

Each law returns gauge pressure [Pa] generated by ONE pour at a given depth
[m] below its own free surface. The caller clamps the depth to the pour's
thickness, retaining the full transmitted contribution below that pour.
These models are illustrative, not design-standard formulations.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from math import isfinite
from typing import Protocol


class PressureLaw(Protocol):
    """Per-pour constitutive pressure function (structural typing)."""

    def pressure(self, depth: float, *, height: float, unit_weight: float) -> float:
        """Return pressure [Pa] for 0 <= depth <= height."""

    def break_depths(self, *, height: float, unit_weight: float) -> tuple[float, ...]:
        """Return internal depth knots where the expression changes branch."""


@dataclass(frozen=True, slots=True)
class HydrostaticPressure:
    """Fully fluid contribution p = unit_weight * depth."""

    def pressure(self, depth: float, *, height: float, unit_weight: float) -> float:
        return unit_weight * depth

    def break_depths(self, *, height: float, unit_weight: float) -> tuple[float, ...]:
        return ()


@dataclass(frozen=True, slots=True)
class CappedHydrostaticPressure:
    """Illustrative pressure cap: min(gamma * depth, maximum_pressure)."""

    maximum_pressure: float

    def __post_init__(self) -> None:
        if not isfinite(self.maximum_pressure) or self.maximum_pressure <= 0:
            raise ValueError('maximum_pressure must be positive and finite [Pa]')

    def pressure(self, depth: float, *, height: float, unit_weight: float) -> float:
        return min(unit_weight * depth, self.maximum_pressure)

    def break_depths(self, *, height: float, unit_weight: float) -> tuple[float, ...]:
        d = self.maximum_pressure / unit_weight
        return (d,) if 0 < d < height else ()


@dataclass(frozen=True, slots=True)
class PowerLawPressure:
    """Illustrative nonlinear profile p = gamma*h*(depth/h)**exponent.

    Exponent 1 is hydrostatic; no physical justification for other exponents
    is assumed. This is useful for numerical/visualization experiments.
    """

    exponent: float = 2.0

    def __post_init__(self) -> None:
        if not isfinite(self.exponent) or self.exponent <= 0:
            raise ValueError('exponent must be positive and finite')

    def pressure(self, depth: float, *, height: float, unit_weight: float) -> float:
        return unit_weight * height * (depth / height) ** self.exponent

    def break_depths(self, *, height: float, unit_weight: float) -> tuple[float, ...]:
        return ()


@dataclass(frozen=True, slots=True)
class TabulatedPressure:
    """Piecewise-linear gauge pressure from depth/pressure pairs.

    Depths are relative to the *top of this pour* in metres, starting at 0.
    For a pour thicker than the last supplied depth, pressure is held at its
    last value. Thus supply depths covering the pour for intended results.
    """

    points: tuple[tuple[float, float], ...]

    def __post_init__(self) -> None:
        if len(self.points) < 2 or self.points[0][0] != 0:
            raise ValueError('At least two points are required, starting at depth 0')
        previous = -1.0
        for depth, pressure in self.points:
            if not isfinite(depth) or not isfinite(pressure) or pressure < 0 or depth <= previous:
                raise ValueError('Depths must be finite and increasing; pressures finite and >= 0')
            previous = depth
        if self.points[0][1] != 0:
            raise ValueError('Gauge pressure must be zero at the free surface (depth 0)')

    def pressure(self, depth: float, *, height: float, unit_weight: float) -> float:
        for (d0, p0), (d1, p1) in zip(self.points, self.points[1:]):
            if depth <= d1:
                return p0 + (p1 - p0) * max(0.0, (depth - d0) / (d1 - d0))
        return self.points[-1][1]

    def break_depths(self, *, height: float, unit_weight: float) -> tuple[float, ...]:
        return tuple(d for d, _ in self.points[1:] if 0 < d < height)


@dataclass(frozen=True, slots=True)
class CallablePressure:
    """Custom depth law; ``function(depth, height, unit_weight) -> Pa``.

    Supply ``knots`` (depths in metres) at changes of analytical branch,
    cusps, or discontinuities. The function must return finite nonnegative
    pressure. Numerical integration uses adaptive Simpson quadrature.
    """

    function: Callable[[float, float, float], float]
    knots: tuple[float, ...] = ()

    def __post_init__(self) -> None:
        if any(not isfinite(d) or d <= 0 for d in self.knots):
            raise ValueError('knots must be positive finite depths')

    def pressure(self, depth: float, *, height: float, unit_weight: float) -> float:
        return float(self.function(depth, height, unit_weight))

    def break_depths(self, *, height: float, unit_weight: float) -> tuple[float, ...]:
        return tuple(d for d in self.knots if 0 < d < height)
